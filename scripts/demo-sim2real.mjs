#!/usr/bin/env node

/**
 * Start the local Sim2Real presentation stack with isolated, disposable state.
 *
 * This launcher is intentionally protocol-only: the worker is the CUDA-free
 * Mock implementation and the BoardAgent is read-only. It does not download a
 * simulator, execute user supplied commands, or claim that an X5 is connected.
 * Operators can provide RDK_SIM2REAL_MICRODUCK_ROOT/URL in the environment (or
 * .env, loaded by run-with-env) when the browser scene is available.
 */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';

const root = process.cwd();
const scratch = mkdtempSync(path.join(os.tmpdir(), 'rdk-sim2real-demo-'));
const scratchLedger = path.join(scratch, 'ledger');
const useExistingStorage = process.env.RDK_SIM2REAL_DEMO_USE_EXISTING_STORAGE === '1';
const configuredStorage = useExistingStorage
  ? String(process.env.RDK_SIM2REAL_STORAGE_DIR || '').trim()
  : '';
const ignoredStorage = String(process.env.RDK_SIM2REAL_STORAGE_DIR || '').trim();
const storageDir = configuredStorage || scratchLedger;
if (!configuredStorage) {
  mkdirSync(scratchLedger, { recursive: true, mode: 0o700 });
  // A disposable simulated device makes the deployment page demonstrable
  // end-to-end: plan creation and the read-only BoardAgent gate are visible
  // without ever implying that a physical X5 is connected.
  writeFileSync(
    path.join(scratchLedger, 'devices.json'),
    JSON.stringify(
      [
        {
          id: 'x5-demo',
          name: 'RDK X5 演示板（模拟）',
          host: '127.0.0.1',
          username: 'demo',
          status: 'connected',
          lastCheckedAt: new Date().toISOString(),
          boardPlatform: 'rdk-x5',
          boardModel: 'RDK X5 (simulated)',
          boardOsVersion: '6.1.0-rdk-demo',
        },
      ],
      null,
      2,
    ),
    { mode: 0o600 },
  );
}
const env = {
  ...process.env,
  // Keep a presentation run isolated from a developer's normal ledger and
  // worker receipts. Explicit storage/runner/resource variables remain
  // available for an operator who intentionally supplies them; auth and
  // deployment mode are pinned to the local demo boundary below.
  RDK_SIM2REAL_STORAGE_DIR: storageDir,
  RDK_SIM2REAL_BIND_HOST: '127.0.0.1',
  RDK_SIM2REAL_DEPLOYMENT: 'local',
  RDK_SIM2REAL_SSO_REQUIRED: '0',
  RDK_SIM2REAL_SSO_ENABLED: '0',
  RDK_SIM2REAL_AUTH_MODE: '',
  RDK_SIM2REAL_REQUIRE_MICRODUCK: '0',
  RDK_SIM2REAL_LOCAL_RUNNER_URL:
    process.env.RDK_SIM2REAL_LOCAL_RUNNER_URL || 'http://127.0.0.1:19090/train',
  RDK_SIM2REAL_LOCAL_RUNNER_MODE: process.env.RDK_SIM2REAL_LOCAL_RUNNER_MODE || 'mock',
  RDK_SIM2REAL_MOCK_DATA_DIR:
    process.env.RDK_SIM2REAL_MOCK_DATA_DIR || path.join(scratch, 'mock-worker'),
  RDK_SIM2REAL_MOCK_PORT: process.env.RDK_SIM2REAL_MOCK_PORT || '19090',
  RDK_SIM2REAL_BOARD_AGENT_URL:
    process.env.RDK_SIM2REAL_BOARD_AGENT_URL || 'http://127.0.0.1:19100',
  RDK_SIM2REAL_BOARD_AGENT_PORT: process.env.RDK_SIM2REAL_BOARD_AGENT_PORT || '19100',
  RDK_SIM2REAL_PORT: process.env.RDK_SIM2REAL_PORT || '18102',
};

const children = new Set();
let shuttingDown = false;

function cleanup() {
  // The directory is generated by this process and contains only demo state.
  // Remove it on normal exit so repeated presentations do not accumulate data
  // under the system temporary directory.
  rmSync(scratch, { recursive: true, force: true });
}
process.once('exit', cleanup);

function start(label, args) {
  const child = spawn(process.execPath, ['scripts/run-with-env.mjs', ...args], {
    cwd: root,
    env,
    stdio: 'inherit',
  });
  children.add(child);
  child.once('error', (error) => {
    console.error(`[demo:${label}] failed to start: ${error.message}`);
    if (!shuttingDown) shutdown(1);
  });
  child.once('exit', (code, signal) => {
    children.delete(child);
    if (shuttingDown) return;
    if (signal) {
      console.error(`[demo:${label}] stopped by ${signal}`);
      shutdown(1);
      return;
    }
    if (code) {
      console.error(`[demo:${label}] exited with code ${code}`);
      shutdown(code);
    }
  });
}

async function waitForReady() {
  const checks = [
    ['mock worker', 'http://127.0.0.1:' + env.RDK_SIM2REAL_MOCK_PORT + '/healthz'],
    ['BoardAgent', 'http://127.0.0.1:' + env.RDK_SIM2REAL_BOARD_AGENT_PORT + '/healthz'],
    ['Web', 'http://127.0.0.1:' + env.RDK_SIM2REAL_PORT + '/readyz'],
  ];
  const deadline = Date.now() + 15_000;
  let lastError = '';
  while (Date.now() < deadline && !shuttingDown) {
    let ready = true;
    for (const [label, url] of checks) {
      try {
        const response = await fetch(url, { signal: AbortSignal.timeout(1_000) });
        if (!response.ok) {
          ready = false;
          lastError = `${label} HTTP ${response.status}`;
        }
      } catch (error) {
        ready = false;
        lastError = `${label}: ${error instanceof Error ? error.message : String(error)}`;
      }
    }
    if (ready) {
      console.log('[demo] ready: Web + Mock worker + read-only BoardAgent');
      return;
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  if (!shuttingDown) {
    console.error(`[demo] services did not become ready within 15s${lastError ? ` (${lastError})` : ''}`);
    shutdown(1);
  }
}

function shutdown(code = 0) {
  if (shuttingDown) return;
  shuttingDown = true;
  for (const child of children) child.kill('SIGTERM');
  // Do not leave a terminal hanging if a child ignores SIGTERM.
  setTimeout(() => process.exit(code), 1_000).unref();
}

process.once('SIGINT', () => shutdown(0));
process.once('SIGTERM', () => shutdown(0));

console.log('[demo] starting isolated Sim2Real presentation stack');
// The query pins MicroDuck + presentation mode for a deterministic projector
// run, even if a previous browser session stored a different product choice.
console.log(`[demo] web: http://127.0.0.1:${env.RDK_SIM2REAL_PORT}/?demo=1`);
console.log('[demo] flow: overview → simulation/replay → Mock protocol run → telemetry/evaluation → X5 preflight gate');
console.log('[demo] telemetry sample: MicroDuck 页面按钮载入合成 61D/14D 证据；examples/telemetry-sample.jsonl 属于 RDK Duck');
console.log(
  configuredStorage
    ? '[demo] using explicit storage (opt-in); device registry is not modified'
    : ignoredStorage
      ? '[demo] ignoring RDK_SIM2REAL_STORAGE_DIR; set RDK_SIM2REAL_DEMO_USE_EXISTING_STORAGE=1 to opt in'
    : '[demo] seeded disposable x5-demo (simulated); preflight remains mock-only and cannot enable motors',
);
console.log('[demo] Mock and BoardAgent are explicitly non-production; Ctrl-C stops all demo processes.');

start('mock-worker', ['node', 'services/sim2real-web/mock-local-worker.mjs']);
start('board-agent', ['node', 'services/sim2real-web/local-board-agent.mjs']);
start('web', ['node', '--import', 'tsx/esm', 'services/sim2real-web/server.ts']);
void waitForReady();
